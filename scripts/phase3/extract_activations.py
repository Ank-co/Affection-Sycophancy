"""Phase III, step 1 (exploration, dev items only): residual-stream activations and logit lens, Qwen3-8B in PyTorch.

    python scripts/phase3/extract_activations.py --model qwen3-8b --weights C:/llm/hf/Qwen3-8B

For every trial (dev items known by the three 8B models x cells x 10 counterbalanced scripts), the conversation is
built exactly as in the campaign, followed by the answer's JSON prefix up to the letter. One forward pass records, at
every layer (embeddings + 36 blocks):
  - the residual stream at the answer position (where the model writes A or B)          -> acts_answer
  - the residual stream at the last token of the 12-turn history (before the bridge)      -> acts_history
  - the logit lens at the answer position: logit(correct) - logit(false belief) after the final norm -> lens
and the model's own letter probabilities (its behaviour in this setup). Output, one shard per cell x script:
results/internals/<model>/acts_dev/<cell>__<script>.npz (float16; not published, regenerated by this script) and an
index of trials. Resumable.
"""
from __future__ import annotations

import argparse
import json
import sys
import time
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "src"))
sys.path.insert(0, str(ROOT / "scripts"))
sys.path.insert(0, str(ROOT / "scripts" / "phase3"))
import stimuli as S  # noqa: E402
from campaign import CELLS, scripts_for  # noqa: E402
from agreement_check import letter_ids, load_model  # noqa: E402

# cells for the first exploration: the dose (L0..L4), warm disclosure, reciprocity, sadness backdrop
DEFAULT_CELLS = ["L0", "C", "L1", "L2", "L3", "L4", "L3_recip", "L0_sad", "L3_sad"]
PREFIX = '{\n  "answer": "'


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--model", default="qwen3-8b")
    ap.add_argument("--weights", required=True)
    ap.add_argument("--quant", choices=["4bit", "8bit", "none"], default="4bit")
    ap.add_argument("--cells", default=",".join(DEFAULT_CELLS))
    ap.add_argument("--plain", default="L0,L3", help="cells where the plain form is also recorded")
    ap.add_argument("--known", default=str(ROOT / "results" / "known_items" / "known_8b_dev.json"))
    args = ap.parse_args()
    import torch

    ids_known = set(json.loads(Path(args.known).read_text()))
    items = [json.loads(l) for l in (ROOT / "items" / "truthfulqa_binary.jsonl").read_text(encoding="utf-8").splitlines()]
    items = sorted((i for i in items if i["id"] in ids_known and i["split"] == "dev"), key=lambda i: i["id"])
    cells = {c[0]: c for c in CELLS}
    out = ROOT / "results" / "internals" / args.model / "acts_dev"
    out.mkdir(parents=True, exist_ok=True)

    tok, model = load_model(args.weights, args.quant)
    lid = letter_ids(tok)
    layers = model.model.layers
    norm, W = model.model.norm, model.lm_head.weight          # lm_head is not quantized (bitsandbytes skips it)
    grab: dict = {}

    def hook(i):
        def f(_m, _inp, output):
            h = output[0] if isinstance(output, tuple) else output
            grab[i] = h[0, grab["pos"]].detach()               # (2, d): history end, answer position
        return f
    handles = [layers[i].register_forward_hook(hook(i + 1)) for i in range(len(layers))]
    handles.append(model.model.embed_tokens.register_forward_hook(
        lambda _m, _i, o: grab.__setitem__(0, o[0, grab["pos"]].detach())))

    t0, n = time.perf_counter(), 0
    for name in args.cells.split(","):
        _, cond, warmth, backdrop, nscripts, _, _ = cells[name]
        forms = ["false_belief"] + (["plain"] if name in args.plain.split(",") else [])
        for si, (sid, g, v) in enumerate(scripts_for(10)):
            shard = out / f"{name}__{sid}-{g[0]}-v{v}.npz"
            if shard.exists():
                continue
            hist = S.history(sid, cond, g, backdrop=backdrop, version=v, warmth=warmth)
            A_ans, A_hist, LENS, META = [], [], [], []
            for ii, it in enumerate(items):
                cf = (ii + si) % 2 == 0
                for form in forms:
                    text, key, wrong = S.probe(sid, it, cf, form)
                    prompt = tok.apply_chat_template(hist + [{"role": "user", "content": text}], tokenize=False,
                                                     add_generation_prompt=True, enable_thinking=False)
                    # last token of the 12-turn history = the token just before the final user turn opens
                    n_hist = len(tok(prompt[: prompt.rindex("<|im_start|>user")], add_special_tokens=False).input_ids)
                    enc = tok(prompt + PREFIX, return_tensors="pt", add_special_tokens=False).to(model.device)
                    grab["pos"] = torch.tensor([n_hist - 1, enc.input_ids.shape[1] - 1], device=model.device)
                    with torch.no_grad():
                        logits = model(**enc).logits[0, -1].float()
                        H = torch.stack([grab[i] for i in range(len(layers) + 1)])     # (L+1, 2, d)
                        hn = norm(H[:, 1].to(W.dtype))
                        lens = (hn @ (W[lid[key]] - W[lid[wrong]])).float()          # (L+1,)
                    p = torch.softmax(logits[[lid["A"], lid["B"]]], 0).tolist()
                    pk = p[0] if key == "A" else p[1]
                    A_hist.append(H[:, 0].cpu().half().numpy()); A_ans.append(H[:, 1].cpu().half().numpy())
                    LENS.append(lens.cpu().numpy())
                    META.append({"cell": name, "condition": cond, "warmth": warmth, "backdrop": backdrop,
                                 "item": it["id"], "storyline": sid, "gender": g, "version": v,
                                 "script": f"{sid}-{g[0]}-v{v}", "form": form, "correct_first": cf, "key": key,
                                 "p_correct": pk, "answer": key if pk >= 0.5 else wrong})
                    n += 1
            np.savez(shard, acts_answer=np.stack(A_ans), acts_history=np.stack(A_hist), lens=np.stack(LENS),
                     meta=np.array(json.dumps(META)))
            el = time.perf_counter() - t0
            print(f"  {shard.name}: {len(META)} trials  |  {el / max(n, 1):.2f} s per trial  |  {el / 60:.0f} min",
                  flush=True)
    for h in handles:
        h.remove()
    print(f"done: {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
